-- MySQL 8.x / InnoDB / utf8mb4
-- ERD에 표시되지 않은 MEMBER, ACCOUNT 참조는 FK를 생성하지 않았습니다.
-- ID는 애플리케이션 신규 INSERT 편의를 위해 AUTO_INCREMENT로 설정했습니다.

CREATE TABLE IF NOT EXISTS PRODUCT (
    PRODUCT_ID BIGINT NOT NULL AUTO_INCREMENT,
    PRODUCT_NAME VARCHAR(100),
    PRODUCT_TYPE VARCHAR(20),
    BASE_INTEREST_RATE DECIMAL(7,4),
    PREFERENTIAL_CONDITION VARCHAR(500),
    TERM_MONTHS SMALLINT,
    MINIMUM_AMOUNT BIGINT,
    EARLY_TERMINATION_RATE DECIMAL(7,4),
    STATUS VARCHAR(20),
    CREATED_AT DATETIME,
    UPDATED_AT DATETIME,
    PRIMARY KEY (PRODUCT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PRODUCTCARD (
    CARD_ID BIGINT NOT NULL AUTO_INCREMENT,
    MEMBER_ID BIGINT,
    ACCOUNT_ID BIGINT,
    CARD_NUMBER VARCHAR(19),
    CARD_TYPE VARCHAR(20),
    CARD_NAME VARCHAR(100),
    CREDIT_LIMIT BIGINT,
    STATUS VARCHAR(20),
    ISSUED_AT DATE,
    EXPIRES_AT DATE,
    CREATED_AT DATETIME,
    UPDATED_AT DATETIME,
    PRIMARY KEY (CARD_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS LOAN (
    LOAN_ID BIGINT NOT NULL AUTO_INCREMENT,
    MEMBER_ID BIGINT,
    REPAYMENT_ACCOUNT_ID BIGINT,
    LOAN_TYPE VARCHAR(30),
    REQUESTED_AMOUNT BIGINT,
    APPROVED_AMOUNT BIGINT,
    ANNUAL_INTEREST_RATE DECIMAL(7,4),
    TERM_MONTHS SMALLINT,
    REPAYMENT_METHOD VARCHAR(30),
    EMPLOYMENT_STATUS VARCHAR(30),
    ANNUAL_INCOME BIGINT,
    STATUS VARCHAR(20),
    REVIEWED_BY BIGINT,
    APPLIED_AT DATETIME,
    REVIEWED_AT DATETIME,
    STARTED_AT DATE,
    MATURITY_DATE DATE,
    REJECTION_REASON VARCHAR(500),
    CREATED_AT DATETIME,
    UPDATED_AT DATETIME,
    PRIMARY KEY (LOAN_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PRODUCT_SUBSCRIPTION (
    SUBSCRIPTION_ID BIGINT NOT NULL AUTO_INCREMENT,
    MEMBER_ID BIGINT,
    PRODUCT_ID BIGINT,
    ACCOUNT_ID BIGINT,
    PRINCIPAL_AMOUNT BIGINT,
    MONTHLY_PAYMENT BIGINT,
    SUBSCRIBED_AT DATE,
    MATURITY_DATE DATE,
    EXPECTED_INTEREST BIGINT,
    STATUS VARCHAR(20),
    CANCELLED_AT DATETIME,
    CREATED_AT DATETIME,
    UPDATED_AT DATETIME,
    PRIMARY KEY (SUBSCRIPTION_ID),
    CONSTRAINT FK_SUBSCRIPTION_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS LOAN_REPAYMENT_SCHEDULE (
    SCHEDULE_ID BIGINT NOT NULL AUTO_INCREMENT,
    LOAN_ID BIGINT,
    INSTALLMENT_NO SMALLINT,
    DUE_DATE DATE,
    PRINCIPAL_AMOUNT BIGINT,
    INTEREST_AMOUNT BIGINT,
    TOTAL_AMOUNT BIGINT,
    STATUS VARCHAR(20),
    PAID_AT DATETIME,
    CREATED_AT DATETIME,
    UPDATED_AT DATETIME,
    PRIMARY KEY (SCHEDULE_ID),
    CONSTRAINT FK_SCHEDULE_LOAN FOREIGN KEY (LOAN_ID) REFERENCES LOAN(LOAN_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS CARD_USAGE_HISTORY (
    CARD_USAGE_ID BIGINT NOT NULL AUTO_INCREMENT,
    CARD_ID BIGINT,
    MERCHANT_NAME VARCHAR(100),
    MERCHANT_CATEGORY VARCHAR(50),
    AMOUNT BIGINT,
    USED_AT DATETIME,
    APPROVAL_NUMBER VARCHAR(30),
    STATUS VARCHAR(20),
    CREATED_AT DATETIME,
    PRIMARY KEY (CARD_USAGE_ID),
    CONSTRAINT FK_CARD_USAGE_CARD FOREIGN KEY (CARD_ID) REFERENCES PRODUCTCARD(CARD_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE INDEX IDX_SUBSCRIPTION_MEMBER ON PRODUCT_SUBSCRIPTION (MEMBER_ID);
CREATE INDEX IDX_CARD_MEMBER ON PRODUCTCARD (MEMBER_ID);
CREATE INDEX IDX_CARD_USAGE_USED_AT ON CARD_USAGE_HISTORY (CARD_ID, USED_AT);
CREATE INDEX IDX_LOAN_MEMBER ON LOAN (MEMBER_ID);
CREATE INDEX IDX_SCHEDULE_LOAN_DUE ON LOAN_REPAYMENT_SCHEDULE (LOAN_ID, DUE_DATE);


CREATE TABLE loan_application (

    APPLICATION_ID BIGINT NOT NULL AUTO_INCREMENT,
    PRODUCT_ID BIGINT NOT NULL,

    APPLICANT_USERNAME VARCHAR(150) NOT NULL,

    REQUESTED_AMOUNT DECIMAL(19, 0) NOT NULL,
    REQUESTED_MONTHS INT NOT NULL,

    AGREED_TO_TERMS BOOLEAN NOT NULL,

    STATUS VARCHAR(20) NOT NULL,
    CREATED_AT DATETIME(6) NOT NULL,

    PRIMARY KEY (APPLICATION_ID),

    CONSTRAINT FK_LOAN_APPLICATION_PRODUCT
        FOREIGN KEY (PRODUCT_ID)
        REFERENCES LOAN_PRODUCT(ID),

    INDEX IDX_LOAN_APPLICATION_USERNAME
        (APPLICANT_USERNAME),

    INDEX IDX_LOAN_APPLICATION_STATUS
        (STATUS)
);